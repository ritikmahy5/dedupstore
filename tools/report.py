def section_e8(res):
    tags = res.tags("E8")
    if not tags:
        return "## E8 — Checkpoint dedup study\n\nNo results yet.\n"
    rows = []
    for tag in tags:
        r = res.get("E8", tag)
        rows.append([tag, res.cell(r, "final.dedup_ratio", "{:.3f}", False),
                     res.cell(r, "total.logical_bytes", "{:.0f}", False, 1 / 2**20),
                     res.cell(r, "final.unique_data_bytes", "{:.0f}", False, 1 / 2**20)])
    out = "## E8 — Checkpoint dedup study\n\n" + table(
        ["run", "dedup ratio", "logical (MiB)", "unique data (MiB)"], rows)
    for tag in tags:
        r = res.get("E8", tag)
        m = r["summary"]["median"]
        labels = r["dataset"].get("versions", "").split(",")
        files = sorted({k.split(".file.", 1)[1].rsplit(".", 1)[0] for k in m if ".file." in k})
        if not files:
            continue
        out += ("\n### %s\n\nNew data bytes per checkpoint (MiB), and for each file the share of its "
                "bytes in chunks that no earlier checkpoint has:\n\n" % tag)
        steps = [[l, res.cell(r, l + ".logical_bytes", "{:.1f}", False, 1 / 2**20),
                  res.cell(r, l + ".new_data_bytes", "{:.1f}", False, 1 / 2**20)] for l in labels]
        out += table(["checkpoint", "logical (MiB)", "new data (MiB)"], steps) + "\n"
        per_file = []
        for f in files:
            size = m.get("%s.file.%s.bytes" % (labels[-1], f), 0)
            later = labels[1:]
            total = sum(m.get("%s.file.%s.bytes" % (l, f), 0) for l in later)
            fresh = sum(m.get("%s.file.%s.new_bytes" % (l, f), 0) for l in later)
            per_file.append([f, res.link(r, "{:.3f}".format(size / 2**20)),
                             res.link(r, "{:.1%}".format(fresh / total)) if total else "-"])
        out += table(["file", "size in last checkpoint (MiB)",
                      "new share, checkpoints after the first"], per_file)
    return out


def section_e9(res):
    rows = []
    points = []
    for tag in res.tags("E9"):
        if not tag.startswith("open-"):
            continue
        r = res.get("E9", tag)
        m = r["summary"]["median"]
        points.append((m["containers"], m["open_s"]))
        rows.append([tag, res.cell(r, "open_s", "{:.3f}"), res.cell(r, "containers", "{:.0f}", False),
                     res.cell(r, "blobs", "{:.0f}", False), res.cell(r, "index_bytes_per_blob", "{:.1f}", False),
                     res.cell(r, "unique_data_bytes", "{:.1f}", False, 1 / 2**30)])
    out = "## E9 — Open time and index memory\n\n" + table(
        ["repository", "open s", "containers", "blobs", "index bytes/blob", "unique data (GiB)"], rows)
    if len(points) >= 2:
        n = len(points)
        sx = sum(x for x, _ in points); sy = sum(y for _, y in points)
        sxx = sum(x * x for x, _ in points); sxy = sum(x * y for x, y in points)
        slope = (n * sxy - sx * sy) / (n * sxx - sx * sx)
        intercept = (sy - slope * sx) / n
        containers_500g = 500e9 / (4 * 2**20)
        out += ("\nLeast-squares fit over the medians above: open_s = %.4g + %.4g x containers. At 4 MiB "
                "containers, 500 GB of unique data is about %.0f containers, which the fit puts at %.1f s "
                "(an extrapolation from at most 100 GiB).\n" %
                (intercept, slope, containers_500g, intercept + slope * containers_500g))
    return out


