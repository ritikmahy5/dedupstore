def section_micro(res):
    rows = []
    for tag in res.tags("micro"):
        r = res.get("micro", tag)
        m = r["summary"]["median"]
        for key in sorted(m):
            name = key.rsplit(".", 1)[0]
            if key.endswith("bytes_per_second"):
                rows.append([name, res.cell(r, key, "{:.2f}", True, 1 / 1e9), "GB/s", "-"])
            elif key.endswith("items_per_second"):
                # With 5 (odd) repetitions the median of ns/op is exactly 1e9 / median ops/s.
                rows.append([name, res.cell(r, key, "{:.1f}", True, 1 / 1e6), "M ops/s",
                             res.link(r, "{:.1f}".format(1e9 / m[key]))])
    return ("## Microbenchmarks\n\n" + table(["benchmark", "median [min-max]", "unit", "ns/op"], rows) +
            "\nBM_Fixed does no per-byte work (the fixed chunker only returns its size), so its rate is "
            "loop overhead, not a data rate (`bench/micro/chunker_bench.cc`).\n")


