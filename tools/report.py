def section_s4prune(res):
    """The next version's transfer with and without subtree pruning (s4_prune.sbatch)."""
    def query_kib(r):
        m = r["summary"]["median"]
        return (m.get("next.wire.HAVE", 0) + m.get("next.wire.HAVE_TREES", 0)) / 1024

    rows = []
    for workload in ["small", "big"]:
        for cell in ["l0.5-b1000", "l40-b1000", "l40-b100", "l40-b10"]:
            off = res.get("S4prune", "%s-%s-p0" % (workload, cell))
            on = res.get("S4prune", "%s-%s-p1" % (workload, cell))
            if off is None or on is None:
                continue
            p = on["params"]
            s_off = off["summary"]["median"]["next.seconds"]
            s_on = on["summary"]["median"]["next.seconds"]
            same_put = (off["summary"]["median"]["next.payload_bytes"] ==
                        on["summary"]["median"]["next.payload_bytes"])
            rows.append([on["dataset"]["name"], p["one_way_latency_ms"], p["mbit"],
                         res.cell(off, "next.seconds", "{:.3f}"), res.cell(on, "next.seconds", "{:.3f}"),
                         res.link(on, "{:.2f}".format(s_off / s_on)),
                         res.link(off, "{:.0f}".format(query_kib(off))),
                         res.link(on, "{:.0f}".format(query_kib(on))),
                         res.link(on, "{:.1f}".format(query_kib(off) / query_kib(on))),
                         res.cell(on, "next.payload_bytes", "{:.0f}", False, 1 / 1024),
                         "yes" if same_put else "no",
                         res.cell(on, "next.trees_checked", "{:.0f}", False),
                         res.cell(on, "next.subtrees_pruned", "{:.0f}", False)])
    return ("## S4prune — Replication with and without subtree pruning\n\n"
            "The next version's transfer over SimulatedLink at W = 8, after the base was sent over an "
            "unlimited link. Query KiB: HAVE plus HAVE_TREES frames on the wire. The ratios divide "
            "without by with pruning. Same PUT: whether both sent the same blob payload bytes.\n\n" +
            table(["dataset", "one-way ms", "Mbit/s", "s without", "s with", "speedup",
                   "query KiB without", "query KiB with", "query ratio", "PUT KiB", "same PUT",
                   "trees asked", "subtrees pruned"], rows))


def section_s4prune2(res):
    """S4prune's pruned transfers, the build it measured against the reviewed one (s4_prune2.sbatch)."""
    def query(r):
        m = r["summary"]["median"]
        return m.get("next.wire.HAVE", 0) + m.get("next.wire.HAVE_TREES", 0)

    rows = []
    for workload in ["small", "big"]:
        for cell in ["l0.5-b1000", "l40-b1000", "l40-b100", "l40-b10"]:
            runs = {run: res.get("S4prune2", "%s-%s-%s" % (workload, cell, run))
                    for run in ["old-a", "new-a", "new-b", "old-b"]}
            present = [r for r in runs.values() if r is not None]
            if not present:
                continue
            mean = {}
            for build in ["old", "new"]:
                vals = [runs[build + "-" + p]["summary"]["median"]["next.seconds"] for p in "ab"
                        if runs[build + "-" + p] is not None]
                mean[build] = sum(vals) / len(vals) if vals else None
            p = present[0]["params"]
            same = (len({query(r) for r in present}) == 1 and
                    len({r["summary"]["median"]["next.payload_bytes"] for r in present}) == 1)
            rows.append([present[0]["dataset"]["name"], p["one_way_latency_ms"], p["mbit"]] +
                        [res.cell(runs[run], "next.seconds", "{:.3f}")
                         for run in ["old-a", "new-a", "new-b", "old-b"]] +
                        [res.link(present[0], "{:.3f}".format(mean["new"] / mean["old"]))
                         if mean["new"] and mean["old"] else "-",
                         res.link(present[0], "{:.0f}".format(query(present[0]) / 1024)),
                         "yes" if same else "no"])
    return ("## S4prune2 — Pruned replication before and after the review's fixes\n\n"
            "The next version's transfer with pruning on, at W = 8, after the base went over an unlimited "
            "link: S4prune's build (old, 61d9cac) and the reviewed one (new), in the order old a, new a, new "
            "b, old b. The ratio divides the mean of the new medians by the mean of the old ones (below 1: "
            "new is faster). Same bytes: whether every run sent the same query (HAVE plus HAVE_TREES) and "
            "PUT payload bytes.\n\n" +
            table(["dataset", "one-way ms", "Mbit/s", "s old a", "s new a", "s new b", "s old b",
                   "new / old", "query KiB", "same bytes"], rows))


def section_s6split(res):
    """Ingest with and without splitting large files, the overhead A/B, and restores (s6_split.sbatch)."""
    def mean_mb(runs):
        vals = [r["summary"]["median"]["total.mb_per_s"] for r in runs if r is not None]
        return sum(vals) / len(vals) if vals else None

    rows = []
    for dataset in ["one8g", "ckpt"]:
        for t in ["4", "16"]:
            runs = {run: res.get("S6split", "%s-t%s-%s" % (dataset, t, run))
                    for run in ["off-a", "on-a", "on-b", "off-b"]}
            if not any(runs.values()):
                continue
            off = mean_mb([runs["off-a"], runs["off-b"]])
            on = mean_mb([runs["on-a"], runs["on-b"]])
            any_on = runs["on-a"] or runs["on-b"]
            roots = {k: v for r in runs.values() if r is not None
                     for k, v in r["summary"]["median"].items() if k.endswith(".root48")}
            same = all(len({r["summary"]["median"].get(k) for r in runs.values() if r is not None}) == 1
                       for k in roots)
            split_keys = [k for k in any_on["summary"]["median"] if k.endswith(".files_split")]
            queued_keys = [k for k in any_on["summary"]["median"] if k.endswith(".segments_queued")]
            files_split = sum(any_on["summary"]["median"][k] for k in split_keys)
            queued = sum(any_on["summary"]["median"][k] for k in queued_keys)
            rows.append([dataset, t] + [res.cell(runs[run], "total.mb_per_s", "{:.0f}")
                                        for run in ["off-a", "off-b", "on-a", "on-b"]] +
                        [res.link(any_on, "{:.2f}".format(on / off)) if on and off else "-",
                         res.link(any_on, "{:.0f}".format(files_split)),
                         res.link(any_on, "{:.0f}".format(queued)), "yes" if same else "no"])
    one = res.get("S6split", "one8g-t1")
    kernel = [[run, res.cell(res.get("S6split", "kernel-t16-" + run), "total.mb_per_s", "{:.0f}")]
              for run in ["old-a", "new-a", "new-b", "old-b"] if res.get("S6split", "kernel-t16-" + run)]
    restore = [[mode, res.cell(res.get("S6split", "restore-one8g-" + mode), "mb_per_s", "{:.0f}")]
               for mode in ["off", "on"] if res.get("S6split", "restore-one8g-" + mode)]
    return ("## S6split — Large files split across workers\n\n"
            "Ingest in memory at an 8 KiB average, MB/s of the whole run, with splitting off and at 64 MiB "
            "(on), in the order off a, on a, on b, off b. The ratio divides the mean of the on medians by "
            "the mean of the off medians. Files split and runs queued (for a worker other than the "
            "splitter, which may still store a few itself) are summed over a run's versions. Same root: whether every version's root "
            "fingerprint (its first 48 bits) is the same in every run.\n\n" +
            table(["dataset", "threads", "off a", "off b", "on a", "on b", "on / off", "files split",
                   "runs queued", "same root"], rows) +
            ("\nThe 8 GiB file at 1 thread: %s MB/s.\n" % res.cell(one, "total.mb_per_s", "{:.0f}")
             if one else "") +
            "\nlinux-6.10 at 16 threads, the commit before splitting (old) and this one "
            "(new):\n\n" +
            table(["build and pass", "MB/s"], kernel) +
            "\nRestore of the 8 GiB file from a disk repository backed up with 16 threads:\n\n" +
            table(["splitting", "restore MB/s"], restore))


def section_s6split2(res):
    """Splitting as S6split measured it against the commit that reserves segment buffers
    (s6_split2.sbatch)."""
    rows = []
    for config in ["one8g-on", "ckpt-on", "one8g-off"]:
        runs = {run: res.get("S6split2", "%s-%s" % (config, run))
                for run in ["old-a", "new-a", "new-b", "old-b"]}
        if not any(runs.values()):
            continue
        mean = {}
        for build in ["old", "new"]:
            vals = [runs[build + "-" + p]["summary"]["median"]["total.mb_per_s"] for p in "ab"
                    if runs[build + "-" + p] is not None]
            mean[build] = sum(vals) / len(vals) if vals else None
        any_r = next(r for r in runs.values() if r is not None)
        ratio = (res.link(any_r, "{:.3f}".format(mean["new"] / mean["old"]))
                 if mean["new"] and mean["old"] else "-")
