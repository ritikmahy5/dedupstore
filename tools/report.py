def section_e1(res):
    rows = []
    series = []
    for tag in res.tags("E1"):
        r = res.get("E1", tag)
        labels = r["dataset"].get("versions", "").split(",")
        new = [k for k in r["summary"]["median"] if k.endswith(".new_data_bytes")]
        meta = sum(r["summary"]["median"].get(k.replace("new_data", t), 0)
                   for k in new for t in ("new_tree", "new_recipe"))
        data = sum(r["summary"]["median"][k] for k in new)
        rows.append([tag, res.cell(r, "final.dedup_ratio", "{:.2f}", False),
                     res.cell(r, "final.unique_data_bytes", "{:.0f}", False, 1 / 2**20),
                     res.link(r, "{:.2%}".format(meta / (meta + data) if data else 0))])
        series.append([tag] + [res.cell(r, l + ".dedup_ratio", "{:.2f}", False) for l in labels])
    out = "## E1 — Content-defined vs fixed chunking\n\n" + table(
        ["dataset-chunker", "dedup ratio (all versions)", "unique data (MiB)",
         "tree and recipe share of new bytes"], rows)
    out += "\nDedup ratio after each version (cumulative logical / unique data):\n"
    for dataset in sorted({t.rsplit("-", 1)[0] for t in res.tags("E1")}):
        group = [s for s in series if s[0].rsplit("-", 1)[0] == dataset]
        labels = res.get("E1", group[0][0])["dataset"].get("versions", "").split(",")
        out += "\n" + table([dataset] + labels, group)
    return out


