AB_CONFIGS = [("64K", "4"), ("64K", "16"), ("64K", "32"), ("8K", "16"), ("8K", "32")]


def ab_means(res, experiment, builds, avg, t):
    """For one configuration: each build's result cells by pass, and the mean of its medians."""
    cells = {(b, p): res.get(experiment, "%s-avg-%s-t%s-%s" % (b, avg, t, p))
             for b in builds for p in ["a", "b"]}
    means = {}
    for b in builds:
        vals = [cells[(b, p)]["summary"]["median"]["total.mb_per_s"]
                for p in ["a", "b"] if cells[(b, p)] is not None]
        means[b] = sum(vals) / len(vals) if vals else None
    return cells, means


def section_ab(res, experiment, title, change,
               old_build="the commit before the sharded pending map"):
    """Same-node comparison of two builds (bench/slurm/ab_common.sh; D99)."""
    rows = []
