#!/usr/bin/env python3
"""Generates docs/RESULTS.md from bench/results/ (BENCHMARKS.md section 2). Never edit RESULTS.md
by hand: change this script or rerun an experiment.

    tools/report.py [--results bench/results] [--out docs/RESULTS.md]

For each experiment and configuration tag (the last part of a run id) the latest result is used.
Every number is a link to the result file it comes from. Timings are shown as median [min-max] over
the measured runs; counts that do not vary between runs are shown once. Standard library only.
"""
import argparse
import glob
import json
import os
import re

HEADER = """# dedupstore — results

Generated by `tools/report.py` from `bench/results/`; do not edit by hand. Numbers come only from
Linux x86-64 runs on Northeastern's Explorer cluster inside SLURM jobs (D37). Each table cell links
to the result file it was read from, which records the run id, commit, machine, compiler, flags,
dataset, parameters, every sample, and the summary. Timings are median [min-max] over 5 measured
runs after one warm-up (BENCHMARKS.md section 2). Where a configuration was run more than once
(the reruns of D99), its latest run is shown; the earlier ones stay in `bench/results/`.
Predictions and outcomes are in BENCHMARKS.md section 5.
"""


class Results:
    def __init__(self, root, rel_prefix):
        self.latest = {}  # (experiment, tag) -> (run_id, result)
        self.rel_prefix = rel_prefix
        for path in glob.glob(os.path.join(root, "*", "*.json")):
            with open(path) as f:
                r = json.load(f)
            tag = r["run_id"].split("-", 3)[3]
            key = (r["experiment"], tag)
            if key not in self.latest or r["run_id"] > self.latest[key][0]:
                self.latest[key] = (r["run_id"], r)

    def tags(self, experiment):
        return sorted(t for (e, t) in self.latest if e == experiment)

    def get(self, experiment, tag):
        return self.latest.get((experiment, tag), (None, None))[1]

    def link(self, r, text):
        return "[%s](%s/%s/%s.json)" % (text, self.rel_prefix, r["experiment"], r["run_id"])

    def cell(self, r, key, fmt="{:.3g}", spread=True, scale=1.0):
        """Median [min-max] of counter `key`, linked; '-' if absent."""
        if r is None or key not in r["summary"]["median"]:
            return "-"
        med = r["summary"]["median"][key] * scale
        lo = r["summary"]["min"][key] * scale
        hi = r["summary"]["max"][key] * scale
        text = fmt.format(med)
        if spread and lo != hi:
            text += " [" + fmt.format(lo) + "-" + fmt.format(hi) + "]"
        return self.link(r, text)


def table(headers, rows):
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


